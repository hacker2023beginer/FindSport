-- Карточки спортивных мероприятий (ТЗ п. 4.2.6–4.2.8, 4.6.5, 4.9, 5.3),
-- предложения с ценами, медиафайлы (п. 4.1.7) и избранное пользователей (п. 4.2.5, 4.9.8).

CREATE TABLE event (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version               BIGINT       NOT NULL DEFAULT 0,
    provider_id           BIGINT       NOT NULL REFERENCES provider (id),
    type                  VARCHAR(20)  NOT NULL,
    status                VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    title_ru              VARCHAR(200) NOT NULL,
    title_en              VARCHAR(200),
    description_ru        TEXT         NOT NULL,
    description_en        TEXT,
    conditions_ru         TEXT         NOT NULL,
    conditions_en         TEXT,
    program_ru            TEXT,
    program_en            TEXT,
    skill_level_ru        VARCHAR(200),
    skill_level_en        VARCHAR(200),
    starts_at             TIMESTAMPTZ  NOT NULL,
    ends_at               TIMESTAMPTZ,
    -- Место проведения: область, район, населенный пункт, улица, дом (п. 7.6)
    region_id             BIGINT       NOT NULL REFERENCES region (id),
    district              VARCHAR(100),
    locality              VARCHAR(100) NOT NULL,
    street                VARCHAR(150) NOT NULL,
    building              VARCHAR(20)  NOT NULL,
    age_min               INTEGER,
    age_max               INTEGER,
    -- NULL — без ограничения числа участников (п. 4.9.6)
    participant_limit     INTEGER,
    registration_deadline TIMESTAMPTZ,
    contact_phone         VARCHAR(13),
    contact_email         VARCHAR(254),
    rejection_reason      TEXT,
    published_at          TIMESTAMPTZ,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_event_type CHECK (type IN ('COMPETITION', 'TRAINING', 'MASTER_CLASS', 'RACE', 'TOURNAMENT', 'CAMP', 'OTHER')),
    CONSTRAINT ck_event_status CHECK (status IN ('DRAFT', 'ON_MODERATION', 'PUBLISHED', 'REJECTED', 'ARCHIVED')),
    CONSTRAINT ck_event_period CHECK (ends_at IS NULL OR ends_at >= starts_at),
    CONSTRAINT ck_event_age CHECK (
        (age_min IS NULL OR age_min >= 0) AND (age_max IS NULL OR age_max >= 0)
        AND (age_min IS NULL OR age_max IS NULL OR age_max >= age_min)),
    CONSTRAINT ck_event_limit CHECK (participant_limit IS NULL OR participant_limit > 0),
    CONSTRAINT ck_event_contacts CHECK (contact_phone IS NOT NULL OR contact_email IS NOT NULL),
    CONSTRAINT ck_event_phone CHECK (contact_phone ~ '^\+375[0-9]{9}$')
);

CREATE INDEX ix_event_provider ON event (provider_id);
CREATE INDEX ix_event_region ON event (region_id);
-- Публичная выдача: только опубликованные, сортировка по новизне (п. 4.7.3)
CREATE INDEX ix_event_status_published ON event (status, published_at DESC);
CREATE INDEX ix_event_starts_at ON event (starts_at);
-- Фильтр по городу (точное совпадение без учета регистра, п. 4.7.2)
CREATE INDEX ix_event_locality ON event (lower(locality));
-- Полнотекстовый поиск по частичному совпадению (п. 4.7.1, 4.7.4)
CREATE INDEX ix_event_title_ru_trgm ON event USING gin (lower(title_ru) gin_trgm_ops);
CREATE INDEX ix_event_title_en_trgm ON event USING gin (lower(title_en) gin_trgm_ops);
CREATE INDEX ix_event_description_ru_trgm ON event USING gin (lower(description_ru) gin_trgm_ops);
CREATE INDEX ix_event_description_en_trgm ON event USING gin (lower(description_en) gin_trgm_ops);
CREATE INDEX ix_event_locality_trgm ON event USING gin (lower(locality) gin_trgm_ops);
CREATE INDEX ix_event_street_trgm ON event USING gin (lower(street) gin_trgm_ops);

CREATE TABLE event_sport (
    event_id BIGINT NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    sport_id BIGINT NOT NULL REFERENCES sport (id),
    PRIMARY KEY (event_id, sport_id)
);

CREATE INDEX ix_event_sport_sport ON event_sport (sport_id);

-- Предложения (варианты участия) с ценой; заявка ссылается на выбранное предложение (п. 4.2.9)
CREATE TABLE event_offer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version    BIGINT        NOT NULL DEFAULT 0,
    event_id   BIGINT        NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    title_ru   VARCHAR(200)  NOT NULL,
    title_en   VARCHAR(200),
    price      NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_event_offer_price CHECK (price >= 0),
    -- Цель составного FK из booking: предложение обязано принадлежать мероприятию заявки
    CONSTRAINT ux_event_offer_id_event UNIQUE (id, event_id)
);

CREATE INDEX ix_event_offer_event_price ON event_offer (event_id, price);

-- Фото (jpg), документы (docx) и видеоссылки на Google Drive (п. 4.1.7).
-- Файлы хранятся вне исполняемых каталогов, в БД — только ключ хранилища (п. 4.13.7).
CREATE TABLE event_media (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version           BIGINT        NOT NULL DEFAULT 0,
    event_id          BIGINT        NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    type              VARCHAR(20)   NOT NULL,
    storage_key       VARCHAR(500),
    original_filename VARCHAR(255),
    content_type      VARCHAR(100),
    size_bytes        BIGINT,
    video_url         VARCHAR(2048),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_event_media_type CHECK (type IN ('IMAGE', 'DOCUMENT', 'VIDEO_LINK')),
    CONSTRAINT ck_event_media_payload CHECK (
        (type = 'VIDEO_LINK' AND video_url IS NOT NULL)
        OR (type <> 'VIDEO_LINK' AND storage_key IS NOT NULL AND size_bytes IS NOT NULL))
);

CREATE INDEX ix_event_media_event ON event_media (event_id);

CREATE TABLE user_favorite_event (
    user_id  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    event_id BIGINT NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, event_id)
);

CREATE INDEX ix_user_favorite_event_event ON user_favorite_event (event_id);
