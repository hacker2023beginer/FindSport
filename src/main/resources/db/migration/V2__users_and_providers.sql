-- Учетные записи (ТЗ п. 4.1.12, 4.2.2–4.2.5, 4.10.1–4.10.2, 4.13.2)
-- и профили поставщиков услуг — организаций и тренеров (п. 4.2.6, 4.10.3–4.10.6, 5.2).

CREATE TABLE users (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version                 BIGINT       NOT NULL DEFAULT 0,
    email                   VARCHAR(254) NOT NULL,
    -- Только стойкий хэш с индивидуальной солью (BCrypt), п. 4.13.2
    password_hash           VARCHAR(100) NOT NULL,
    -- Гость — неавторизованный посетитель и в БД не хранится
    role                    VARCHAR(20)  NOT NULL DEFAULT 'USER',
    display_name            VARCHAR(100),
    phone                   VARCHAR(13),
    region_id               BIGINT REFERENCES region (id),
    preferred_language      VARCHAR(2)   NOT NULL DEFAULT 'RU',
    email_verified          BOOLEAN      NOT NULL DEFAULT FALSE,
    blocked                 BOOLEAN      NOT NULL DEFAULT FALSE,
    failed_login_attempts   INTEGER      NOT NULL DEFAULT 0,
    locked_until            TIMESTAMPTZ,
    personalization_consent BOOLEAN      NOT NULL DEFAULT FALSE,
    email_notifications     BOOLEAN      NOT NULL DEFAULT TRUE,
    deletion_requested_at   TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_lower CHECK (email = lower(email)),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'PROVIDER', 'MODERATOR', 'ADMIN')),
    CONSTRAINT ck_users_language CHECK (preferred_language IN ('RU', 'EN')),
    CONSTRAINT ck_users_phone CHECK (phone ~ '^\+375[0-9]{9}$'),
    CONSTRAINT ck_users_failed_attempts CHECK (failed_login_attempts >= 0)
);

CREATE INDEX ix_users_region ON users (region_id);

-- Спортивные интересы пользователя (п. 4.10.1, 4.8.1)
CREATE TABLE user_sport_interest (
    user_id  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    sport_id BIGINT NOT NULL REFERENCES sport (id),
    PRIMARY KEY (user_id, sport_id)
);

CREATE INDEX ix_user_sport_interest_sport ON user_sport_interest (sport_id);

CREATE TABLE provider (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version          BIGINT       NOT NULL DEFAULT 0,
    owner_id         BIGINT       NOT NULL REFERENCES users (id),
    type             VARCHAR(20)  NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    name_ru          VARCHAR(200) NOT NULL,
    name_en          VARCHAR(200),
    description_ru   TEXT         NOT NULL,
    description_en   TEXT,
    region_id        BIGINT       NOT NULL REFERENCES region (id),
    -- Адрес (п. 7.6) или территория оказания услуг (п. 5.2)
    district         VARCHAR(100),
    locality         VARCHAR(100),
    street           VARCHAR(150),
    building         VARCHAR(20),
    service_area_ru  TEXT,
    service_area_en  TEXT,
    working_hours_ru VARCHAR(500) NOT NULL,
    working_hours_en VARCHAR(500),
    contact_phone    VARCHAR(13),
    contact_email    VARCHAR(254),
    -- Объем публикуемых контактов определяет владелец (п. 4.10.6)
    phone_public     BOOLEAN      NOT NULL DEFAULT FALSE,
    email_public     BOOLEAN      NOT NULL DEFAULT FALSE,
    rejection_reason TEXT,
    published_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_provider_type CHECK (type IN ('ORGANIZATION', 'TRAINER')),
    CONSTRAINT ck_provider_status CHECK (status IN ('DRAFT', 'ON_MODERATION', 'PUBLISHED', 'REJECTED', 'ARCHIVED')),
    CONSTRAINT ck_provider_location CHECK (locality IS NOT NULL OR service_area_ru IS NOT NULL),
    CONSTRAINT ck_provider_contacts CHECK (contact_phone IS NOT NULL OR contact_email IS NOT NULL),
    CONSTRAINT ck_provider_phone CHECK (contact_phone ~ '^\+375[0-9]{9}$')
);

CREATE INDEX ix_provider_owner ON provider (owner_id);
CREATE INDEX ix_provider_region ON provider (region_id);
CREATE INDEX ix_provider_status ON provider (status);
CREATE INDEX ix_provider_name_ru_trgm ON provider USING gin (lower(name_ru) gin_trgm_ops);
CREATE INDEX ix_provider_name_en_trgm ON provider USING gin (lower(name_en) gin_trgm_ops);

-- Виды спорта поставщика (п. 4.10.3, 5.2)
CREATE TABLE provider_sport (
    provider_id BIGINT NOT NULL REFERENCES provider (id) ON DELETE CASCADE,
    sport_id    BIGINT NOT NULL REFERENCES sport (id),
    PRIMARY KEY (provider_id, sport_id)
);

CREATE INDEX ix_provider_sport_sport ON provider_sport (sport_id);
