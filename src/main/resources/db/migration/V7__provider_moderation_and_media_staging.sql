-- Неделя 4: подтверждение профилей поставщиков и медиаматериалы карточек.

-- Подтверждение и модерация профилей организаций и тренеров (ТЗ п. 4.10.5, 4.14).
-- Как и у мероприятий, строка provider хранит только одобренную (публичную) версию, а существенные
-- правки опубликованного профиля ждут решения в снимке отправки (решение PM по повторной модерации).
CREATE TABLE provider_moderation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      BIGINT      NOT NULL DEFAULT 0,
    provider_id  BIGINT      NOT NULL REFERENCES provider (id) ON DELETE CASCADE,
    submitted_by BIGINT      NOT NULL REFERENCES users (id),
    snapshot     JSONB       NOT NULL,
    decision     VARCHAR(20),
    reason       TEXT,
    moderator_id BIGINT REFERENCES users (id),
    decided_at   TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_provider_moderation_decision CHECK (decision IN ('APPROVED', 'REJECTED')),
    -- Причина отклонения обязательна (п. 4.14.3)
    CONSTRAINT ck_provider_moderation_reason CHECK (decision <> 'REJECTED' OR reason IS NOT NULL),
    CONSTRAINT ck_provider_moderation_decided CHECK (
        (decision IS NULL AND decided_at IS NULL AND moderator_id IS NULL)
        OR (decision IS NOT NULL AND decided_at IS NOT NULL AND moderator_id IS NOT NULL))
);

CREATE INDEX ix_provider_moderation_provider ON provider_moderation (provider_id, created_at DESC);
-- Не более одной нерассмотренной отправки на профиль
CREATE UNIQUE INDEX ux_provider_moderation_pending ON provider_moderation (provider_id) WHERE decision IS NULL;

-- Замена и добавление медиафайлов — существенное изменение (п. 4.14.1): новый материал не виден
-- посетителям до одобрения, а удаляемый остается в публикации до решения модератора.
ALTER TABLE event_media ADD COLUMN published BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE event_media ADD COLUMN removal_requested BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE event_media ADD CONSTRAINT ck_event_media_removal CHECK (NOT removal_requested OR published);

DROP INDEX ix_event_media_event;
CREATE INDEX ix_event_media_event ON event_media (event_id, id);
