-- Заявки на мероприятия (ТЗ п. 4.2.9–4.2.11, 4.9.6–4.9.7)
-- и журнал модерации карточек (п. 4.13.4, 4.14).

CREATE TABLE booking (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version       BIGINT       NOT NULL DEFAULT 0,
    event_id      BIGINT       NOT NULL REFERENCES event (id),
    user_id       BIGINT       NOT NULL REFERENCES users (id),
    offer_id      BIGINT       NOT NULL,
    contact_name  VARCHAR(100) NOT NULL,
    contact_phone VARCHAR(13),
    contact_email VARCHAR(254),
    status        VARCHAR(20)  NOT NULL DEFAULT 'SUBMITTED',
    -- created_at — дата подачи заявки (п. 4.2.9)
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_booking_offer FOREIGN KEY (offer_id, event_id) REFERENCES event_offer (id, event_id),
    CONSTRAINT ck_booking_status CHECK (status IN ('SUBMITTED', 'CONFIRMED', 'REJECTED')),
    CONSTRAINT ck_booking_contacts CHECK (contact_phone IS NOT NULL OR contact_email IS NOT NULL),
    CONSTRAINT ck_booking_phone CHECK (contact_phone ~ '^\+375[0-9]{9}$')
);

-- Подсчет занятых мест (п. 4.9.7) и обработка заявок поставщиком (п. 4.2.10)
CREATE INDEX ix_booking_event_status ON booking (event_id, status);
-- История заявок пользователя (п. 4.2.5)
CREATE INDEX ix_booking_user_created ON booking (user_id, created_at DESC);

-- Каждая отправка на модерацию — запись со снимком карточки (jsonb).
-- Сравнение со снимком последней одобренной версии дает Diff-режим (п. 4.14.3).
CREATE TABLE event_moderation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      BIGINT      NOT NULL DEFAULT 0,
    event_id     BIGINT      NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    submitted_by BIGINT      NOT NULL REFERENCES users (id),
    snapshot     JSONB       NOT NULL,
    decision     VARCHAR(20),
    reason       TEXT,
    moderator_id BIGINT REFERENCES users (id),
    decided_at   TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_event_moderation_decision CHECK (decision IN ('APPROVED', 'REJECTED')),
    -- Причина отклонения обязательна (п. 4.14.3)
    CONSTRAINT ck_event_moderation_reason CHECK (decision <> 'REJECTED' OR reason IS NOT NULL),
    CONSTRAINT ck_event_moderation_decided CHECK (
        (decision IS NULL AND decided_at IS NULL AND moderator_id IS NULL)
        OR (decision IS NOT NULL AND decided_at IS NOT NULL AND moderator_id IS NOT NULL))
);

CREATE INDEX ix_event_moderation_event ON event_moderation (event_id, created_at DESC);
-- Не более одной нерассмотренной отправки на карточку
CREATE UNIQUE INDEX ux_event_moderation_pending ON event_moderation (event_id) WHERE decision IS NULL;
