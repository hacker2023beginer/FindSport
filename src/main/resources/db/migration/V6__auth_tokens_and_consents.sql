-- Регистрация, подтверждение e-mail и восстановление доступа (ТЗ п. 4.2.2, 4.10.2, 4.13.10–4.13.11).

-- Момент принятия пользовательского соглашения и политики обработки персональных данных
-- при регистрации (п. 4.6.8, 4.13.10). Учетные записи, созданные администратором, могут не иметь отметки.
ALTER TABLE users ADD COLUMN consents_accepted_at TIMESTAMPTZ;

-- Одноразовые ссылки из писем. Хранится только SHA-256 токена: полный токен есть лишь в письме
-- и не попадает ни в БД, ни в журналы (п. 4.13.13).
CREATE TABLE user_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version     BIGINT      NOT NULL DEFAULT 0,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    purpose     VARCHAR(30) NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_user_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_user_token_purpose CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET'))
);

CREATE INDEX ix_user_token_user_purpose ON user_token (user_id, purpose) WHERE used_at IS NULL;
