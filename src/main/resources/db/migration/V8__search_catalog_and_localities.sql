CREATE TABLE locality (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version     BIGINT        NOT NULL DEFAULT 0,
    name_ru     VARCHAR(100)  NOT NULL,
    name_en     VARCHAR(100),
    region_code VARCHAR(50)   NOT NULL REFERENCES region (code),
    latitude    NUMERIC(9, 6) NOT NULL,
    longitude   NUMERIC(9, 6) NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ux_locality_name_ru UNIQUE (name_ru),
    CONSTRAINT ck_locality_latitude CHECK (latitude >= 51 AND latitude <= 56.5),
    CONSTRAINT ck_locality_longitude CHECK (longitude >= 23 AND longitude <= 33.5)
);

-- Поиск населенного пункта по названию без учета регистра: метка карты и фильтр по городу
CREATE INDEX ix_locality_name_lower ON locality (lower(name_ru));
CREATE INDEX ix_locality_region ON locality (region_code);

