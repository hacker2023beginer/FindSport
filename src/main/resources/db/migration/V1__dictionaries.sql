-- Справочники регионов и видов спорта (ТЗ п. 4.5.3) с локализованными наименованиями (п. 4.1.6, 4.5.7).
-- pg_trgm — регистронезависимый поиск по частичному совпадению через GIN-индексы (п. 4.7.4).

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE region (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version    BIGINT       NOT NULL DEFAULT 0,
    code       VARCHAR(50)  NOT NULL,
    name_ru    VARCHAR(200) NOT NULL,
    name_en    VARCHAR(200),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_region_code UNIQUE (code)
);

CREATE TABLE sport (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version    BIGINT       NOT NULL DEFAULT 0,
    code       VARCHAR(50)  NOT NULL,
    name_ru    VARCHAR(200) NOT NULL,
    name_en    VARCHAR(200),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_sport_code UNIQUE (code)
);

CREATE INDEX ix_sport_name_ru_trgm ON sport USING gin (lower(name_ru) gin_trgm_ops);
CREATE INDEX ix_sport_name_en_trgm ON sport USING gin (lower(name_en) gin_trgm_ops);

