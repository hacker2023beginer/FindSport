package by.findsport.domain;

/**
 * Роли авторизованных учетных записей (ТЗ п. 4.1.12, Приложение 2).
 * Роль «Гость» соответствует неаутентифицированному посетителю и не хранится в БД.
 */
public enum UserRole {
    /** Зарегистрированный пользователь. */
    USER,
    /** Представитель организации или тренер (поставщик услуг). */
    PROVIDER,
    MODERATOR,
    ADMIN
}
