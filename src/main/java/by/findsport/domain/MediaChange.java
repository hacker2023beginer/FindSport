package by.findsport.domain;

/**
 * Состояние медиаматериала относительно публичной версии карточки (Diff-режим, ТЗ п. 4.14.3).
 */
public enum MediaChange {
    /** Опубликован и не изменялся. */
    UNCHANGED,
    /** Добавлен автором и ждет одобрения; посетителям не виден. */
    ADDED,
    /** Удален автором; посетителям виден до одобрения изменений. */
    REMOVED
}
