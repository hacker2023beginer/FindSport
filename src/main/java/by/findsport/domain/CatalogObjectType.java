package by.findsport.domain;

/**
 * Тип объекта публичного каталога (ТЗ п. 4.6.2–4.6.4, 4.10.3): спортивное мероприятие,
 * организация или тренер. Объединение типов в одном поиске отражает структуру
 * общедоступной части Платформы (п. 4.6.2).
 */
public enum CatalogObjectType {
    /** Спортивное мероприятие (раздел 2 ТЗ: «объект»). */
    EVENT,
    /** Организация — поставщик услуг (п. 4.10.3). */
    ORGANIZATION,
    /** Тренер — поставщик услуг (п. 4.10.3). */
    TRAINER;

    /** Поставщик услуг: организация или тренер. */
    public boolean isProvider() {
        return this == ORGANIZATION || this == TRAINER;
    }
}
